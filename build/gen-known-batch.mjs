// Build the embedded card-check table from a QC manifest.
//
// Why this exists: the v1 record carries no checksum, so a single mistyped character in a hand-entered
// card code has roughly a 40% chance of still decoding to a VALID record holding a different valid public
// key. In the giving flow that produces a real-looking deposit address whose key nobody has. The giver
// funds it, every screen says success, and the loss only surfaces when the recipient tries to claim.
//
// We cannot add a checksum to cards already printed. But we DO know the authoritative public key for every
// card we made, and that data is public (it is the QC manifest, which contains no words). Embedding a
// short hash of each one lets the app reject a corrupted code outright, for any corruption, however it was
// entered. Scoped to serials we actually minted, so cards outside the range still work and the standard
// stays open and permissionless.
//
// Output is PUBLIC: truncated hashes of public keys. It reveals nothing that the QR codes do not.
// Run: node gen-known-batch.mjs <QC-manifest.json> [more-manifests...]
import { readFileSync, writeFileSync } from 'node:fs';
import { sha256 } from '@noble/hashes/sha256';
import { hex, base64 } from '@scure/base';

const files = process.argv.slice(2);
if (!files.length) { console.error('usage: node gen-known-batch.mjs <QC-manifest.json> ...'); process.exit(1); }

const TRUNC = 5;   // 40 bits per card: a corrupted key has ~1 in 1.1e12 odds of passing by accident
const byserial = new Map();
for (const f of files) {
  const man = JSON.parse(readFileSync(f, 'utf8'));
  for (const c of man.cards) {
    if (!/^0[23][0-9a-f]{64}$/.test(c.p1Hex)) throw new Error('serial ' + c.serial + ': bad p1Hex');
    const prev = byserial.get(c.serial);
    if (prev && prev !== c.p1Hex) throw new Error('serial ' + c.serial + ' appears twice with different keys');
    byserial.set(c.serial, c.p1Hex);
  }
}
const serials = [...byserial.keys()].sort((a, b) => a - b);

// Batches are NOT one contiguous run: serial ranges are allocated per print job and deliberately leave
// gaps (101-400 then 1000-1299). Split into contiguous segments so each stays a flat blob with no
// per-card serial overhead, and so a gap costs nothing rather than being an error.
const segments = [];
for (const s of serials) {
  const last = segments[segments.length - 1];
  if (last && s === last.end + 1) last.end = s;
  else segments.push({ start: s, end: s });
}
for (const seg of segments) {
  const blob = new Uint8Array((seg.end - seg.start + 1) * TRUNC);
  for (let s = seg.start; s <= seg.end; s++) {
    blob.set(sha256(hex.decode(byserial.get(s))).slice(0, TRUNC), (s - seg.start) * TRUNC);
  }
  seg.hashes = base64.encode(blob);
  seg.count = seg.end - seg.start + 1;
}

const out = `// GENERATED by gen-known-batch.mjs. Do not hand edit.
// Truncated SHA-256 of the compressed public key printed on each card we have minted, grouped into
// contiguous serial segments. PUBLIC data: it says nothing that is not already in the QR codes.
// Purpose: catch a mistyped card code before someone funds an address that no key opens, including on
// cards whose record format carries no checksum of its own. See gen-known-batch.mjs for the reasoning.
export const KNOWN_BATCH = {
  trunc: ${TRUNC},
  segments: [
${segments.map(s => `    { start: ${s.start}, end: ${s.end}, hashes: '${s.hashes}' }`).join(',\n')}
  ]
};
`;
const dest = new URL('known-batch.js', import.meta.url);
writeFileSync(dest, out);
const totalChars = segments.reduce((n, s) => n + s.hashes.length, 0);
console.log('cards:        ' + serials.length + ' across ' + segments.length + ' segment(s)');
for (const s of segments) console.log('              serials ' + s.start + '..' + s.end + '  (' + s.count + ' cards)');
console.log('bytes/card:   ' + TRUNC + '  -> ' + totalChars + ' chars total in the bundle');
console.log('written:      build/known-batch.js');
